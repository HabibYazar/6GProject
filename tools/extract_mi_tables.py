"""Parse the C++ tables out of mmwave-lte-mi-error-model.cc into Python.

Mechanical, because hand-copying 5,800 numbers is a source of silent error
that no test would catch.
"""
import re, sys, textwrap

src = open(sys.argv[1]).read()

def _body(name):
    """The braces of a declaration, matched rather than pattern-guessed.

    `cEcrTable` ends with `}};` on one line and a `\n};` anchor ran past it
    into the next declaration — 426 numbers where 342 were wanted. Counting
    braces cannot make that mistake.
    """
    m = re.search(r"static const [\w:<>]+ " + re.escape(name) + r"\s*(\[[^=]*\])?\s*=\s*\{",
                  src)
    if not m:
        raise SystemExit(f"not found: {name}")
    i = m.end() - 1
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                return re.sub(r"//[^\n]*", "", src[i + 1:j])
    raise SystemExit(f"unbalanced: {name}")

NUM = r"-?\d+\.?\d*(?:[eE][-+]?\d+)?"

def flat(name):
    return [float(x) for x in re.findall(NUM, _body(name))]

def table2d(name, rows, cols):
    vals = [float(x) for x in re.findall(NUM, _body(name))]
    if len(vals) != rows * cols:
        raise SystemExit(f"{name}: got {len(vals)} want {rows*cols}")
    return [vals[i*cols:(i+1)*cols] for i in range(rows)]

def vec(name):
    return [int(float(x)) for x in re.findall(NUM, _body(name))]

# The C++ types matter: these are declared uint8_t/uint16_t and are used as
# ARRAY INDICES. Emitting them as floats makes `bEcrTable[i][ecrId]` a
# TypeError at the first call — which is the good failure; the bad one would
# be a table of indices silently rounding somewhere.
INT_TABLES = {"McsEcrBlerTableMapping", "cbMiSizeTable", "ModulationSchemeForMcs"}

out = {}
for n in ("BlerCurvesEcrMap", "McsEcrBlerTableMapping", "McsEcrTable",
          "cbMiSizeTable", "MI_map_qpsk", "MI_map_qpsk_axis",
          "MI_map_16qam", "MI_map_16qam_axis", "MI_map_64qam",
          "MI_map_64qam_axis", "SpectralEfficiencyForCqi",
          "SpectralEfficiencyForMcs", "ModulationSchemeForMcs"):
    out[n] = [int(v) for v in flat(n)] if n in INT_TABLES else flat(n)
out["cbSizeTable"] = vec("cbSizeTable")
out["bEcrTable"] = table2d("bEcrTable", 9, 38)
out["cEcrTable"] = table2d("cEcrTable", 9, 38)

exp = {"BlerCurvesEcrMap": 38, "McsEcrBlerTableMapping": 29, "McsEcrTable": 29,
       "cbMiSizeTable": 9, "MI_map_qpsk": 797, "MI_map_qpsk_axis": 797,
       "MI_map_16qam": 994, "MI_map_16qam_axis": 994, "MI_map_64qam": 752,
       "MI_map_64qam_axis": 752, "SpectralEfficiencyForCqi": 16,
       "SpectralEfficiencyForMcs": 32, "ModulationSchemeForMcs": 32,
       "cbSizeTable": 188}
for k, n in exp.items():
    got = len(out[k])
    if k == "cbSizeTable":
        print(f"  {k:26} {got}")
        continue
    assert got == n, f"{k}: {got} != {n}"
    print(f"  {k:26} {got} ok")

def fmt(name, v):
    if isinstance(v[0], list):
        rows = ",\n    ".join("[" + ", ".join(repr(x) for x in r) + "]" for r in v)
        return f"{name} = [\n    {rows},\n]\n"
    body = textwrap.fill(", ".join(repr(x) for x in v), 78,
                         initial_indent="    ", subsequent_indent="    ")
    return f"{name} = [\n{body},\n]\n"

with open(sys.argv[2], "w") as fh:
    fh.write('"""Tables lifted verbatim from the engine\'s own error model.\n\n'
             'GENERATED by tools/extract_mi_tables.py from\n'
             '`src/mmwave/model/error-model/mmwave-lte-mi-error-model.cc` in the\n'
             'ns-O-RAN tree. Do not edit by hand and do not re-derive from a\n'
             'specification: 5,800 numbers copied by eye is an error nothing would\n'
             'catch, and a table from TS 36.212 that differs from the one in the\n'
             'binary turns every disagreement into a hunt.\n'
             '\n'
             'Names are the C++ ones so a reader can grep both sides.\n"""\n\n')
    for n in ("MI_map_qpsk_axis", "MI_map_qpsk", "MI_map_16qam_axis", "MI_map_16qam",
              "MI_map_64qam_axis", "MI_map_64qam", "BlerCurvesEcrMap",
              "McsEcrBlerTableMapping", "McsEcrTable", "cbMiSizeTable",
              "cbSizeTable", "SpectralEfficiencyForCqi", "SpectralEfficiencyForMcs",
              "ModulationSchemeForMcs", "bEcrTable", "cEcrTable"):
        fh.write(fmt(n, out[n]) + "\n")
print("written", sys.argv[2])
